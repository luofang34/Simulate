//! Coefficients follow Seidelmann (1982), *Explanatory Supplement to the Astronomical Almanac*
//! (Table 3.222.1), in units of `0.1 milliarcsecond` (`0.0001"`).

use core::f64::consts::{PI, TAU};

pub(super) const ARCSEC_TO_RAD: f64 = PI / (180.0 * 3600.0);
const TENTH_MAS_TO_RAD: f64 = ARCSEC_TO_RAD * 1.0e-4;

struct NutationTerm {
    mult: [i8; 5],
    sp: f64,
    spt: f64,
    ce: f64,
    cet: f64,
}

const fn t(mult: [i8; 5], sp: f64, spt: f64, ce: f64, cet: f64) -> NutationTerm {
    NutationTerm {
        mult,
        sp,
        spt,
        ce,
        cet,
    }
}

