fn wrap_pm_pi(angle_rad: f64) -> f64 {
    let mut wrapped = libm::fmod(angle_rad, TAU);
    if libm::fabs(wrapped) >= PI {
        wrapped -= libm::copysign(TAU, wrapped);
    }
    wrapped
}

fn poly_arg(c0: f64, c1: f64, c2: f64, c3: f64, revs_per_cy: f64, t_cy: f64) -> f64 {
    let secular_as = c0 + (c1 + (c2 + c3 * t_cy) * t_cy) * t_cy;
    wrap_pm_pi(secular_as * ARCSEC_TO_RAD + libm::fmod(revs_per_cy * t_cy, 1.0) * TAU)
}

/// Evaluates IAU-1980 mean obliquity of the ecliptic (radians) at `t_cy` Julian centuries past J2000.0 TDB.
pub(super) fn mean_obliquity_iau1980(t_cy: f64) -> f64 {
    (84_381.448 + (-46.8150 + (-0.000_59 + 0.001_813 * t_cy) * t_cy) * t_cy) * ARCSEC_TO_RAD
}

/// Evaluates IAU-1980 nutation `(dpsi_rad, deps_rad, omega_moon_rad)` at `t_cy` Julian centuries past J2000.0 TDB.
pub(super) fn nutation_iau1980(t_cy: f64) -> (f64, f64, f64) {
    let l = poly_arg(485_866.733, 715_922.633, 31.310, 0.064, 1_325.0, t_cy);
    let lp = poly_arg(1_287_099.804, 1_292_581.224, -0.577, -0.012, 99.0, t_cy);
    let f = poly_arg(335_778.877, 295_263.137, -13.257, 0.011, 1_342.0, t_cy);
    let d = poly_arg(1_072_261.307, 1_105_601.328, -6.891, 0.019, 1_236.0, t_cy);
    let om = poly_arg(450_160.280, -482_890.539, 7.455, 0.008, -5.0, t_cy);

    let (mut dp, mut de) = (0.0_f64, 0.0_f64);
    for entry in IAU1980_TERMS.iter().rev() {
        let [nl, nlp, nf, nd, nom] = entry.mult;
        let arg = f64::from(nl) * l
            + f64::from(nlp) * lp
            + f64::from(nf) * f
            + f64::from(nd) * d
            + f64::from(nom) * om;
        let s = entry.sp + entry.spt * t_cy;
        let c = entry.ce + entry.cet * t_cy;
        let (sin_arg, cos_arg) = libm::sincos(arg);
        if s != 0.0 {
            dp += s * sin_arg;
        }
        if c != 0.0 {
            de += c * cos_arg;
        }
    }
    (dp * TENTH_MAS_TO_RAD, de * TENTH_MAS_TO_RAD, om)
}
