def propeller_system(doc, beta, n):
    spec = doc["bem_design"]
    lo, hi = val(doc["governing_range_075R"])
    rpm_lo, rpm_hi = val(doc["governor_rpm_range"])
    reduction = val(doc["installation_reduction_gear"])
    d_ft = spec["diameter_in"] / 12.0
    j_per_rpm = reduction / 60.0 * d_ft
    rev_per_rpm = 60.0 / reduction
    d5 = d_ft ** 5
    e = f"propulsion/engine[{n}]"
    body = fn(f"{e}/governor-rpm-req", f"""            <sum>
                <value> {rpm_lo} </value>
                <product>
                    <property>fcs/advance-cmd-norm[{n}]</property>
                    <value> {rpm_hi - rpm_lo} </value>
                </product>
            </sum>""")
    body += fn(f"fcs/governor-advance-ratio-{n}", f"""            <quotient>
                <property>velocities/vt-fps</property>
                <product>
                    <property>{e}/governor-rpm-req</property>
                    <value> {j_per_rpm:.6f} </value>
                </product>
            </quotient>""")
    body += fn(f"fcs/governor-power-coefficient-{n}", f"""            <quotient>
                <product>
                    <property>{e}/available-power-hp</property>
                    <value> 550.0 </value>
                </product>
                <product>
                    <property>atmosphere/rho-slugs_ft3</property>
                    <pow>
                        <quotient>
                            <property>{e}/governor-rpm-req</property>
                            <value> {rev_per_rpm:.4f} </value>
                        </quotient>
                        <value> 3.0 </value>
                    </pow>
                    <value> {d5:.1f} </value>
                </product>
            </quotient>""")
    body += fn(f"fcs/governor-rpm-trim-rate-{n}", f"""            <product>
                <difference>
                    <property>{e}/engine-rpm</property>
                    <property>{e}/governor-rpm-req</property>
                </difference>
                <value> 0.01 </value>
            </product>""")
    body += f"""        <integrator name="fcs/governor-rpm-trim-{n}">
            <input> fcs/governor-rpm-trim-rate-{n} </input>
            <c1> 1.0 </c1>
            <clipto>
                <min> -6.0 </min>
                <max>  6.0 </max>
            </clipto>
        </integrator>
"""
    body += fn(f"fcs/governor-blade-angle-{n}", f"""            <max>
                <value> {lo} </value>
                <min>
                    <value> {hi} </value>
                    <sum>
                        <table>
                            <independentVar lookup="row">fcs/governor-advance-ratio-{n}</independentVar>
                            <independentVar lookup="column">fcs/governor-power-coefficient-{n}</independentVar>
                            <tableData>
{table_body(beta)}
                            </tableData>
                        </table>
                        <property>fcs/governor-rpm-trim-{n}</property>
                    </sum>
                </min>
            </max>""", f"{e}/blade-angle")
    return f"""<?xml version="1.0"?>
<!-- Generated by vehicles/tools/part_jsbsim.py from propeller.json ({doc['id']}) for engine position {n}.
     Constant-speed governor: the blade angle is the propeller's equilibrium angle beta(J, Cp) between the
     {lo} and {hi} deg stops (propeller_bem.py beta on the same blade design), plus a slow integral trim on the
     remaining RPM error; the lever selects {rpm_lo:.0f}-{rpm_hi:.0f} engine rpm (ESTIMATED). Being algebraic it holds
     through JSBSim's trim, whose 0.5 s steady-state steps make JSBSim's own RPM-error governor oscillate.
     Reads propulsion/engine[{n}]/available-power-hp from the engine part's system. -->
<system name="{doc['id']}-propeller{n}">
    <channel name="{doc['id']} governor {n}">
{body}    </channel>
</system>
"""


def propeller_catalog(doc, eta):
    spec = doc["bem_design"]
    lo, hi = spec["governing_stops_deg"]
    in_range = [b for b in spec["table_betas_deg"] if lo <= b <= hi]
    best = lambda j: max(eta[(j, b)] for b in in_range)
    max_eta = max(best(j) for j in [round(0.2 * k, 1) for k in range(1, 21)])
    return {
        "kind": "propeller",
        "version": 1,
        "source": {
            "kind": "reference",
            "reference": f"Simulate part {doc['id']} (parts/propellers/{doc['id']}/propeller.json)",
            "revision": None,
        },
        "document": {
            "id": f"propeller.{doc['id'].replace('-', '_')}",
            "version": 1,
            "type": "propeller",
            "model": "propulsion.propeller_efficiency_simple",
            "metadata": {
                "display_name": doc["name"],
                "source": "blade count sourced; diameter, pitch range and blade design estimated (propeller.json); efficiencies from the BEM tables",
                "confidence": "low",
            },
            "parameters": {
                "diameter": f"{spec['diameter_in'] * 0.0254:.3f} m",
                "blade_count": val(doc["blades"]),
                "static_efficiency": round(best(0.2), 3),
                "cruise_efficiency": round(best(1.4), 3),
                "maximum_efficiency": round(max_eta, 3),
                "climb_installation_factor": round(best(0.6) / max_eta, 3),
                "tip_mach_limit": 0.85,
            },
        },
    }


def main():
    part = sys.argv[1]
    if os.path.exists(os.path.join(part, "engine.json")):
        doc = json.load(open(os.path.join(part, "engine.json")))
        write(os.path.join(part, "jsbsim", "engine.xml"), engine_xml(doc))
        for n in POSITIONS:
            write(os.path.join(part, "jsbsim", f"system-{n}.xml"), engine_system(doc, n))
        catalog = engine_catalog(doc)
    else:
        doc = json.load(open(os.path.join(part, "propeller.json")))
        ct, cp, beta, eta = propeller_tables(doc["bem_design"])
        write(os.path.join(part, "jsbsim", "propeller.xml"), propeller_xml(doc, ct, cp))
        for n in POSITIONS:
            write(os.path.join(part, "jsbsim", f"system-{n}.xml"), propeller_system(doc, beta, n))
        catalog = propeller_catalog(doc, eta)
    write(os.path.join(part, "ace", "catalog-entry.json"), json.dumps(catalog, indent=2, ensure_ascii=False) + "\n")
    print(f"generated {part}")


if __name__ == "__main__":
    main()
